export const Table__Users = mysqlTable(
  "users",
  {
    id: autoGeneratedId(),
    organizationId: char("organization_id", { length: 10 }),
    role: userRoleEnum("role").notNull(),
    name: varchar("name", { length: 150 }).notNull(),
    email: varchar("email", { length: 255 }).notNull().unique(),
    password: varchar("password", { length: 255 })
      .notNull()
      .$defaultFn(() => hashPasswordSync(DEFAULT_PASSWORD)),
    username: varchar("username", { length: 255 }).notNull().unique(),
    phone: varchar("phone", { length: 30 }).notNull(),
    employeeCode: char("employee_code", { length: 16 }).unique().notNull(),
    status: userStatusEnum("status").default("UNDER_VERIFICATION").notNull(),
    profilePicture: varchar("profile_picture", { length: 255 }),
    lastLoginAt: timestamp("last_login_at"),
    reportingManagerId: foreignId("reporting_manager"),

    ...tableMetaData("USER"),
  },
  (table) => [
    index("users_employee_code_idx").on(
      table.organizationId,
      table.employeeCode,
    ),

    foreignKey({
      columns: [table.reportingManagerId],
      foreignColumns: [table.id],
      name: "users_reporting_manager_users_id_fk",
    })
      .onDelete("set null")
      .onUpdate("cascade"),
  ],
);

