/**
 * This is used to identify which table the data is from,
 * and if there is any querry we have to do we can understand
 * in which table we have to do the query.
 */
const tableMapper: Record<TableIdentifierToken, string> = {
  USER: "users",
  EMPR: "employee_profile",
  PTPR: "partner_profile",
  EXPR: "experience",
  EDQF: "educational_qualification",
  PRQF: "professional_qualification",
  MNGR: "managerial_relationships",
  STAE: "state",
  DIST: "district",
} as const;

export function identifyTable(
  tableIdentifierToken: TableIdentifierToken,
): string {
  const tableName = tableMapper[tableIdentifierToken];

  if (!tableName) {
    throw new Error("Provide a valid prefix to identify table name.");
  }

  return tableName;
}
