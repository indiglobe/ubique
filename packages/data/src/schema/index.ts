function foreignId(columnName: string) {
  return char(columnName, { length: 10 });
}
function autoGeneratedId() {
  return char("id", { length: 10 })
    .primaryKey()
    .$defaultFn(() => id().toUpperCase());
}
function tableMetaData(tableIdentifierToken: TableIdentifierToken) {
  return {
    createdAt: timestamp("created_at").defaultNow().notNull(),
    updatedAt: timestamp("updated_at")
      .defaultNow()
      .notNull()
      .$onUpdateFn(() => new Date()),
    tableIdentifierToken: char("table_identifier_token", {
      length: 4,
    })
      .notNull()
      .default(tableIdentifierToken),
  };
}

