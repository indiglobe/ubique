const read__OneDistrictSchema = z.object({
  identifier: z.object({
    id: z.string(),
  }),
});

// =====================================
// =====================================
// =====================================
// =====================================
// =====================================

const read__AllDistrictSchema = z
  .object({
    identifier: z
      .object({
        stateId: z.union([z.string(), z.array(z.string())]),
      })
      .optional(),
  })
  .optional();

// =====================================
// =====================================
// =====================================
// =====================================
// =====================================

export {
  //

  read__AllDistrictSchema,
  read__OneDistrictSchema,
};
